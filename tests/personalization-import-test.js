const assert = require('node:assert/strict');
const ai = require('../assets/js/personalization-import.js');
const row = {};
const payload = {status: 'detected', fields: [{kind: 'month'}]};
let callbacks = [], messages = [];
const resolve = (_, callback) => callbacks.push(callback);
const display = result => messages.push(result);
ai.apply(row, payload, true, resolve, display);
assert.throws(() => ai.selection(row), /Várd meg/);
callbacks.shift()({state: 'matched', preset_id: 'actual-local-id'});
assert.equal(ai.selection(row).action, 'auto');
assert.equal(ai.selection(row).payload, payload);
ai.apply(row, payload, false, resolve, display);
assert.equal(ai.selection(row).action, 'preserve');
ai.apply(row, payload, true, resolve, display);
ai.manual(row);
const before = messages.length;
callbacks.shift()({state: 'matched', preset_id: 'stale'});
assert.equal(messages.length, before);
assert.equal(ai.selection(row).action, 'manual');
ai.apply(row, payload, true, resolve, display);
assert.equal(callbacks.length, 0, 'AI toggles never overwrite manual choices');
const second = {};
ai.apply(second, payload, true, resolve, display);
ai.apply(second, null, false, resolve, display);
callbacks.shift()({state: 'matched', preset_id: 'stale'});
assert.equal(ai.selection(second).action, 'preserve', 'Disabling AI invalidates late responses');
ai.apply(second, payload, true, resolve, display);
callbacks.shift()({state: 'review', message: 'Missing mapping'});
assert.equal(ai.selection(second).action, 'preserve');
assert.equal(ai.selection(second).payload, null);
console.log('PASS: pending, auto, off, missing mapping, manual precedence and stale responses.');
