const assert = require('node:assert/strict');
const { preset, bucket, report, campaignKey, revenue } = require('../assets/js/order-attribution.js');
assert.deepEqual(preset('2026-01-05', 'last_month'), ['2025-12-01', '2025-12-31']);
assert.deepEqual(preset('2024-03-01', 'last_month'), ['2024-02-01', '2024-02-29']);
assert.deepEqual(preset('2026-09-28', '7'), ['2026-09-22', '2026-09-28']);
assert.deepEqual(preset('2026-01-01', 'yesterday'), ['2025-12-31', '2025-12-31']);
assert.deepEqual(preset('2026-09-28', 'last_year'), ['2025-01-01', '2025-12-31']);
assert.equal(bucket('2026-01-01', 'week'), '2025-12-29');
assert.equal(bucket('2026-09-06', 'week'), '2026-08-31');
assert.equal(bucket('2026-09-07', 'week'), '2026-09-07');
assert.equal(bucket('2026-09-28', 'month'), '2026-09-01');
const fact = { day: '2026-09-01', platform: 'facebook', channel: 'paid', currency: 'HUF', campaign: 'Bögrék', orders: 2, gross: 100000000, refunds: 10000000 };
const rows = [fact, { ...fact, campaign: '', channel: 'referral', orders: 1, gross: 50000000, refunds: 0 }, { ...fact, currency: 'EUR', orders: 9 }, { ...fact, platform: 'instagram', orders: 1, day: '2026-09-07' }];
const all = report(rows, { currency: 'HUF' }, '2026-09-01', '2026-09-07', 'day');
assert.equal(all.total.orders, 4);
assert.equal(all.periods.length, 7);
assert.equal(all.periods[1].orders, 0, 'Zero-sale periods stay visible');
assert.equal(revenue(all.total), 230000000, 'Refunds deducted, foreign currency excluded');
assert.equal(all.total.tagged, 3);
assert.equal(all.campaigns.length, 3, 'Same campaign on two platforms stays distinguishable');
assert.equal(report(rows, { currency: 'HUF', platform: 'facebook', campaign: campaignKey('Bögrék') }, '2026-09-01', '2026-09-07', 'day').total.orders, 2);
assert.equal(report(rows, { currency: 'HUF', campaign: campaignKey('') }, '2026-09-01', '2026-09-07', 'day').total.orders, 1, 'Unlabelled campaign is independently filterable');
assert.equal(report(rows, { currency: 'HUF', channel: 'paid' }, '2026-09-01', '2026-09-07', 'week').total.orders, 3);
assert.equal(report(rows, { currency: 'HUF' }, '2026-09-01', '2026-09-07', 'week').periods.length, 2);
assert.equal(report(rows, { currency: 'HUF' }, '2026-09-01', '2026-09-07', 'month').periods.length, 1);
const empty = report([], { currency: 'HUF' }, '2026-09-01', '2026-09-07', 'day');
assert.equal(empty.total.orders, 0);
assert.equal(empty.platforms.length, 0);
console.log('PASS: date presets, week/month boundaries, filters, currency, refunds and zero periods.');
